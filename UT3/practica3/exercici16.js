// && és un operador que retorna true si TOTES les condicions que connecta
// son true, si un valor és fals, retornarà fals
let tencgana = true;
let tencmenjar = true;
console.log(tencgana && tencmenjar);

// || és un operador que retorna true si com a mínim UNA condicio es true
let tenctasques = true;
let tencganes = false;
console.log(tenctasques || tencganes);